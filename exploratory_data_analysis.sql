-- What is the total revenue generated for each category? 
SELECT	
	dp.category,
	SUM(fs.sales_amount) AS ttl_sales_by_cat
FROM gold.fact_sales fs
LEFT JOIN gold.dim_product dp
ON fs.product_key = dp.product_key
GROUP BY dp.category
ORDER BY ttl_sales_by_cat DESC;

-- Find total revenue is generated by each customer
SELECT 
	customer_key,
	SUM(sales_amount) AS revenue_by_each_cust
FROM gold.fact_sales
GROUP BY customer_key
ORDER BY revenue_by_each_cust DESC;


-- What is the distribution of sold products across countries

SELECT 
	dc.country,
	dp.product_name,
	COUNT(fs.product_key) AS dist_product
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers dc
ON fs.customer_key = dc.customer_key
LEFT JOIN gold.dim_product dp
ON fs.product_key = dp.product_key
GROUP BY dc.country, dp.product_name


SELECT
    country,
    product_name,
    dist_product AS most_sold_product
FROM (
    SELECT
        dc.country,
        dp.product_name,
        COUNT(fs.product_key) AS dist_product,
        ROW_NUMBER() OVER (
            PARTITION BY dc.country
            ORDER BY COUNT(fs.product_key) DESC
        ) AS rn
    FROM gold.fact_sales fs
    LEFT JOIN gold.dim_customers dc
        ON fs.customer_key = dc.customer_key
    LEFT JOIN gold.dim_product dp
        ON fs.product_key = dp.product_key
    GROUP BY dc.country, dp.product_name
) t
WHERE rn = 1;

-- Which 5 products generate the highest revenue

SELECT 
	dp.product_name,
	fs.*
FROM gold.dim_product dp
INNER JOIN (
SELECT TOP 5
	product_key,
	SUM(sales_amount) AS revenue,
	ROW_NUMBER() OVER(ORDER BY SUM(sales_amount) DESC) AS rn
FROM gold.fact_sales fs
GROUP BY product_key
) fs
ON dp.product_key = fs.product_key


-- What are the 5 worst-performing products in terms of sales?
SELECT 
	dp.product_name,
	fs.*
FROM gold.dim_product dp
INNER JOIN (
SELECT TOP 5
	product_key,
	SUM(sales_amount) AS revenue,
	ROW_NUMBER() OVER(ORDER BY SUM(sales_amount) ASC) AS rn
FROM gold.fact_sales fs
GROUP BY product_key
) fs
ON dp.product_key = fs.product_key

-- Find the top 10 cusotmers who have generated the highest revenue

SELECT TOP 10
	fs.customer_key,
	dc.first_name,
	dc.last_name,
	SUM(sales_amount) AS revenue_by_each_cust
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers dc
ON fs.customer_key = dc.customer_key
GROUP BY fs.customer_key,
		dc.first_name,
		dc.last_name
ORDER BY revenue_by_each_cust DESC;

-- and 3 customers with the fewest orders placed 
SELECT TOP 3
	dc.customer_key,
	dc.first_name,
	dc.last_name,
	COUNT(DISTINCT order_number) AS ttl_orders
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers dc
ON fs.customer_key = dc.customer_key
GROUP BY dc.customer_key,
		dc.first_name,
		dc.last_name
ORDER BY ttl_orders ASC;

